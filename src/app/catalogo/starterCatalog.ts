/**
 * Genera la lista de categorías con conteo para los productos del catálogo inicial.
 */
export function getStarterCategories(): CatalogoCategory[] {
  const counts: Record<string, number> = {};
  for (const p of STARTER_SHOWCASE_PRODUCTS) {
    const key = (p.category || "").trim().toUpperCase();
    counts[key] = (counts[key] || 0) + 1;
  }

  const list: CatalogoCategory[] = Object.keys(counts).map((name) => ({
    id: `cat-${name.toLowerCase()}`,
    name,
    count: counts[name],
  }));

  list.sort((a, b) => a.name.localeCompare(b.name));
  return list;
}
